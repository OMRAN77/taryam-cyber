export function getLang() {
  try { return localStorage.getItem('aiapp_lang') === 'en' ? 'en' : 'ar'; } catch (e) { return 'ar'; }
}

export function setLang(lang) {
  try { localStorage.setItem('aiapp_lang', lang); } catch (e) { /* storage unavailable */ }
}

export function t(key, lang = getLang()) {
  const pair = S[key];
  if (!pair) return key;
  return lang === 'en' ? pair[1] : pair[0];
}

export function pair(key) { return S[key] || [key, key]; }
