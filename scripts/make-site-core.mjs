#!/usr/bin/env node
// Regenerates lab/core/site.js from api/_casino.js: the same site analysis, as an ES
// module, so the casino-check page can analyse a page source the user pasted from
// their own browser when the site blocks our server. Run after editing api/_casino.js.
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export function generate() {
  const src = readFileSync(path.join(ROOT, 'api', '_casino.js'), 'utf8');
  const m = /^module\.exports = \{([^}]+)\};\s*$/m.exec(src);
  if (!m) throw new Error('api/_casino.js: module.exports line not found');
  const body = src.slice(0, m.index).replace(/\/\/ Also copied into lab\/core\/site\.js[^\n]*\n\/\/[^\n]*\n$/, '');
  return '// Generated by scripts/make-site-core.mjs from api/_casino.js. Do not edit.\n' + body.trimEnd() + '\n\nexport {' + m[1] + '};\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(ROOT, 'lab', 'core', 'site.js'), generate());
  console.log('wrote lab/core/site.js');
}
