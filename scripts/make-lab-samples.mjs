#!/usr/bin/env node
// Regenerates lab/samples.js from lab/samples/*.json. The lab page loads samples
// as a module because its CSP (connect-src 'none') blocks fetch(), even same-origin.
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const LAB = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'lab');
const files = { desertGold: 'desert-gold.json', rouletteEuropean: 'roulette-european.json', rouletteAmerican: 'roulette-american.json', desertGoldWeighted: 'desert-gold-weighted.json' };
let out = '// Generated by scripts/make-lab-samples.mjs from lab/samples/*.json. Do not edit.\n';
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name} = ${JSON.stringify(JSON.parse(readFileSync(path.join(LAB, 'samples', file), 'utf8')))};\n`;
}
writeFileSync(path.join(LAB, 'samples.js'), out);
console.log('wrote lab/samples.js');
